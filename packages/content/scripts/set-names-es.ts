/**
 * Regenerates packages/client/src/content/set-names-es.ts: the Spanish name of every card set (an encounter set, a hero's
 * own set) and of every product, keyed by the English name the client prints, for the screens that name them in words
 * (Set up the table's modular tiles and composition rows).
 *
 *   pnpm --filter @mc/content set-names-es [--check]
 *
 * Reads the committed MarvelCDB caches, no network: the English `raw/marvelcdb/<pack>.json` and the Spanish
 * `raw/marvelcdb/es/<pack>.json`. Keeps only the names that differ. `--check` writes nothing and exits 1 when out of date.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

interface RawCard {
  readonly pack_name?: string | null;
  readonly card_set_code?: string | null;
  readonly card_set_name?: string | null;
  readonly linked_card?: RawCard;
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const RAW = path.join(root, "packages/content/raw/marvelcdb");
const OUT = path.join(root, "packages/client/src/content/set-names-es.ts");
const check = process.argv.includes("--check");

const read = (file: string): RawCard[] => {
  const json = JSON.parse(fs.readFileSync(file, "utf8")) as { cards?: RawCard[] };
  return (json.cards ?? []).flatMap((card) => [card, ...(card.linked_card ? [card.linked_card] : [])]);
};

const sets: Record<string, string> = {};
const packs: Record<string, string> = {};
for (const file of fs
  .readdirSync(path.join(RAW, "es"))
  .filter((f) => f.endsWith(".json"))
  .sort()) {
  const english = path.join(RAW, file);
  if (!fs.existsSync(english)) continue;
  const spanishByCode = new Map<string, string>();
  const englishByCode = new Map<string, string>();
  let packEs: string | null = null;
  let packEn: string | null = null;
  for (const card of read(path.join(RAW, "es", file))) {
    packEs ??= card.pack_name ?? null;
    if (card.card_set_code && card.card_set_name) spanishByCode.set(card.card_set_code, card.card_set_name);
  }
  for (const card of read(english)) {
    packEn ??= card.pack_name ?? null;
    if (card.card_set_code && card.card_set_name) englishByCode.set(card.card_set_code, card.card_set_name);
  }
  if (packEn && packEs && packEn !== packEs) packs[packEn] = packEs;
  for (const [code, en] of englishByCode) {
    const es = spanishByCode.get(code);
    if (es && es !== en) sets[en] = es;
  }
}

const table = (record: Record<string, string>): string =>
  Object.entries(record)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([en, es]) => `  ${JSON.stringify(en)}: ${JSON.stringify(es)},`)
    .join("\n");

const body = `/**
 * Spanish card set and product names, by the English name the client prints. GENERATED by
 * packages/content/scripts/set-names-es.ts (raw/marvelcdb/es against raw/marvelcdb); do not hand-edit, rerun it.
 */
export const SET_NAMES_ES: Readonly<Record<string, string>> = {
${table(sets)}
};

export const PACK_NAMES_ES: Readonly<Record<string, string>> = {
${table(packs)}
};
`;

if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== body) {
    console.error("set-names-es.ts is out of date: run pnpm --filter @mc/content set-names-es");
    process.exit(1);
  }
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${Object.keys(sets).length} set names and ${Object.keys(packs).length} product names`);
}
