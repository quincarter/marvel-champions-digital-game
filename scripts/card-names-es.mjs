#!/usr/bin/env node
// Regenerates packages/client/src/content/card-names-es.ts: the Spanish card names the deck builder's search matches (#806).
//
//   node scripts/card-names-es.mjs [--check]
//
// Reads MarvelCDB's public card lists, es.marvelcdb.com and marvelcdb.com, keeps the ids that are cards in
// packages/content/src/data (the pool's `id: cardId("...")` entries) and whose Spanish name differs from the English one,
// and writes them sorted by id. `--check` writes nothing and exits 1 when the file is out of date.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "packages/client/src/content/card-names-es.ts");
const DATA = path.join(root, "packages/content/src/data");
const check = process.argv.includes("--check");

const fetchCards = async (host) => {
  const res = await fetch(`https://${host}/api/public/cards/`, { headers: { "User-Agent": "card-names-es-script" } });
  if (!res.ok) throw new Error(`${host}: HTTP ${res.status}`);
  return new Map((await res.json()).map((card) => [card.code, card.name]));
};

const poolIds = new Set();
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(file);
    else if (entry.name.endsWith(".ts") && !entry.name.endsWith(".test.ts"))
      for (const match of fs.readFileSync(file, "utf8").matchAll(/^\s*id: cardId\("([^"]+)"\)/gm))
        poolIds.add(match[1]);
  }
};
walk(DATA);

const [es, en] = await Promise.all([fetchCards("es.marvelcdb.com"), fetchCards("marvelcdb.com")]);
const names = [...es]
  .filter(
    ([code, name]) =>
      poolIds.has(code) && en.has(code) && name.trim().toLowerCase() !== en.get(code).trim().toLowerCase(),
  )
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

// Quoted as the formatter writes it (single quotes around a name holding double quotes), so the file is format-clean.
const quote = (value) => (value.includes('"') && !value.includes("'") ? `'${value}'` : JSON.stringify(value));

const lines = [
  "/**",
  " * Spanish card names, by card id (a MarvelCDB code), for the deck builder's name search: a Spanish player types",
  ' * "La Balsa" for The Raft (issue #806). Only cards in the pool whose name MarvelCDB prints differently in Spanish.',
  " * GENERATED by scripts/card-names-es.mjs (es.marvelcdb.com against marvelcdb.com); do not hand-edit, rerun it.",
  " * Loaded only when the card language is Spanish (`view/card-names.ts`).",
  " */",
  "export const CARD_NAMES_ES: Readonly<Record<string, string>> = {",
  ...names.map(([code, name]) => `  ${quote(code)}: ${quote(name)},`),
  "};",
  "",
];
const text = lines.join("\n");
if (check) {
  const same = fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") === text;
  console.log(
    same ? "card-names-es.ts is up to date." : "card-names-es.ts is out of date: run scripts/card-names-es.mjs.",
  );
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(OUT, text);
console.log(`Wrote ${names.length} names to ${path.relative(root, OUT)}.`);
